// ============================================================================
//  des.cpp —— DES 算法核心实现（FIPS 46-3）
//  ---------------------------------------------------------------------------
//  实现思路：
//   1. 用一个 64 位无符号整数承载一个分组，所有标准表都按 FIPS 46-3 的
//      1-based 编址（位号 1 = 最高位）书写，由 permute() 统一完成
//      “查表 — 取位 — 拼装”，避免为每张表各写一段循环。
//   2. 加解密共用同一个 cryptBlock()：Feistel 结构的天然对称性使得
//      解密只需把 16 个子密钥按相反顺序送入轮函数。
//   3. 密钥编排把 64 位密钥经 PC-1 压缩为 56 位，拆成两个 28 位半区 C/D，
//      按 SHIFTS 表循环左移后经 PC-2 压缩为 48 位子密钥。
// ============================================================================
