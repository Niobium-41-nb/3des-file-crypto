// ---------------------------- 工具函数 ----------------------------

u64 permute(u64 in, const int* table, int n, int inWidth) {
    u64 out = 0;
    for (int i = 0; i < n; ++i) {
        // table[i] 是 1-based 位号，位号 1 对应 in 的最高位
        out = (out << 1) | ((in >> (inWidth - table[i])) & 1ULL);
    }
    return out;
}

u64 rotateLeft28(u64 v, int n) {
    const u64 MASK = 0x0FFFFFFFULL;  // 低 28 位全 1
    v &= MASK;
    return ((v << n) | (v >> (28 - n))) & MASK;
}

u64 feistel(u32 r, u64 subKey) {
    u64 ex = permute(r, E, 48, 32);  // 1) E 扩展：32 -> 48
    u64 x = ex ^ subKey;             // 2) 与 48 位子密钥按位异或
    u32 s = 0;
    for (int i = 0; i < 8; ++i) {  // 3) 8 个 S 盒并行代换：48 -> 32
        int six = (int)((x >> (42 - 6 * i)) & 0x3F);  // 取出第 i 组 6 位输入
        int row = ((six & 0x20) >> 4) | (six & 0x01);  // 首末两位 -> 行号
        int col = (six >> 1) & 0x0F;                   // 中间四位 -> 列号
        s = (s << 4) | (u32)SBOX[i][row * 16 + col];
    }
    return permute(s, P, 32, 32);  // 4) P 置换：32 -> 32
}

u64 bytesToU64(const std::uint8_t b[BLOCK_SIZE]) {
    u64 v = 0;
    for (int i = 0; i < 8; ++i) v = (v << 8) | b[i];
    return v;
}

void u64ToBytes(u64 v, std::uint8_t b[BLOCK_SIZE]) {
    for (int i = 7; i >= 0; --i) {
        b[i] = (std::uint8_t)(v & 0xFF);
        v >>= 8;
    }
}

// ---------------------------- 核心流程 ----------------------------

void keySchedule(const std::uint8_t key[KEY_SIZE], SubKeys& sk) {
    u64 k = bytesToU64(key);
    u64 cd = permute(k, PC1, 56, 64);      // PC-1：64 -> 56
    u64 c = (cd >> 28) & 0x0FFFFFFFULL;    // 高 28 位 -> C
    u64 d = cd & 0x0FFFFFFFULL;            // 低 28 位 -> D
    for (int i = 0; i < 16; ++i) {
        c = rotateLeft28(c, SHIFTS[i]);    // 循环左移
        d = rotateLeft28(d, SHIFTS[i]);
        u64 cd2 = (c << 28) | d;           // 重新拼成 56 位
        sk.k[i] = permute(cd2, PC2, 48, 56);  // PC-2：56 -> 48
    }
}

// 加密/解密统一实现：decrypt = true 时按逆序取子密钥
static void cryptBlock(const std::uint8_t in[BLOCK_SIZE], std::uint8_t out[BLOCK_SIZE],
                       const SubKeys& sk, bool decrypt) {
    u64 block = bytesToU64(in);                 // 字节流 -> 比特串
    u64 ip = permute(block, IP, 64, 64);        // 初始置换
    u32 l = (u32)(ip >> 32);                    // 左半区 L0
    u32 r = (u32)(ip & 0xFFFFFFFFULL);          // 右半区 R0
    for (int i = 0; i < 16; ++i) {              // 16 轮 Feistel 迭代
        u64 sub = decrypt ? sk.k[15 - i] : sk.k[i];
        u32 nl = r;
        u32 nr = l ^ (u32)feistel(r, sub);      // f(R,K) 与 L 异或
        l = nl;
        r = nr;
    }
    u64 pre = ((u64)r << 32) | l;               // 预输出 R16||L16（左右交换）
    u64 res = permute(pre, IP_INV, 64, 64);     // 逆初始置换
    u64ToBytes(res, out);
}

void encryptBlock(const std::uint8_t in[BLOCK_SIZE], std::uint8_t out[BLOCK_SIZE], const SubKeys& sk) {
    cryptBlock(in, out, sk, false);
}

void decryptBlock(const std::uint8_t in[BLOCK_SIZE], std::uint8_t out[BLOCK_SIZE], const SubKeys& sk) {
    cryptBlock(in, out, sk, true);
}

